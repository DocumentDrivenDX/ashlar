"""Fixed packaged UMF physical carriers; no logical admission or native authority.

Preserves the original generated profiles and provenance. Consumers bind these
six physical roles to their own admitted domain and actual target ownership.
"""
import hashlib
from importlib.resources import files
import json
from pathlib import Path
from .lifecycle import finish

ORIGINAL_LOCAL_PHYSICAL_PROVENANCE='fb2bff45bc7849d298208d0436d99295c01696bdcdd8101f63caa8069e122e9a'
_ROLES=('object_current','edge_current','tombstone','whole_source_history','attempts','manifest')


def original_local_physical_carriers():
    """Validate packaged generated bytes and all original model inputs; no authority grant."""
    root=files('ashlar_host').joinpath('resources','original-commerce-local')
    def read(name,maximum):
        stream=root.joinpath(name).open('rb');primary=None;raw=None
        try:
            raw=stream.read(maximum+1)
            if len(raw)>maximum:raise ValueError('Bounded generated resource required')
        except BaseException as error:primary=error
        finish(primary,[stream.close]);return raw
    raw=read('provenance.json',65536)
    if hashlib.sha256(raw).hexdigest()!=ORIGINAL_LOCAL_PHYSICAL_PROVENANCE:raise ValueError('Original generated provenance differs')
    provenance=json.loads(raw);selected={}
    for row in provenance['resources']:
        value=read(row['resource'],1048576)
        if len(value)!=row['size']or hashlib.sha256(value).hexdigest()!=row['sha256']:
            raise ValueError('Original generated carrier/model bytes differ')
        selected[row['resource']]=value
    generated=json.loads(selected['runtime-carriers.generated.json'])
    if generated['profile']!='ashlar-generated-original-commerce-local-carriers/0.1'or set(generated['carriers'])!=set(_ROLES):
        raise ValueError('Exact six generated local roles required')
    for path,digest in generated['inputs'].items():
        if hashlib.sha256(selected[Path(path).name]).hexdigest()!=digest:raise ValueError('Generated input correspondence differs')
    for role,carrier in generated['carriers'].items():
        layout=carrier['layout']
        if layout['name']!=[role]or layout['partitionBy']or layout['clusterBy']or layout['properties']:
            raise ValueError('Exact reviewed local layout required')
    return generated
